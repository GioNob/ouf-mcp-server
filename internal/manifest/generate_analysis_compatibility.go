//go:build ignore

// Run with go generate from the integration worktree with the predecessor in Git.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"

	"github.com/GioNob/ouf-mcp-server/internal/manifest"
)

func checksum(m *manifest.Snapshot) string {
	sum, err := m.Checksum()
	if err != nil {
		panic(err)
	}
	return sum
}

func historical(predecessor, version string) *manifest.Snapshot {
	raw, err := exec.Command("git", "show", predecessor+":internal/manifest/capabilities.json").Output()
	if err != nil {
		panic(err)
	}
	var old manifest.Snapshot
	if err := json.Unmarshal(raw, &old); err != nil {
		panic(err)
	}
	if old.Version != version {
		panic("unexpected historical manifest: " + old.Version)
	}
	return &old
}

func batchChecksums(m *manifest.Snapshot) [3]string {
	for i, c := range m.Capabilities {
		if c.CapabilityID != "ouf.semantic.search.batch" {
			continue
		}
		if c.PublicationState != "ACTIVE" {
			panic("unexpected published batch baseline")
		}
		active := checksum(m)
		m.Capabilities[i].PublicationState = "INACTIVE"
		inactive := checksum(m)
		m.Capabilities = append(m.Capabilities[:i], m.Capabilities[i+1:]...)
		return [3]string{active, inactive, checksum(m)}
	}
	panic("missing published batch")
}

func main() {
	m, err := manifest.Load()
	if err != nil {
		panic(err)
	}
	if m.Version != "1.19.1-next-discovery-v1" {
		panic("unexpected analysis baseline")
	}
	current := batchChecksums(m)
	service := batchChecksums(historical("de648f1300b39f3339413f88f55ad4854b4f4d52", "1.19.0-next-discovery-v1"))
	history := batchChecksums(historical("2a25eb48566d06ae2952e2feb9fc619592fc7570", "1.18.2-history-limit-v1"))
	previous := batchChecksums(historical("4b395686ab1dccb80e37e63d26a8228b472d05ac", "1.17.0-published-batch-v1"))
	legacy := checksum(historical("ea4033ef04579e5bbd59b897133bffa09bc0a803", "1.16.0-analysis-summary-v2"))
	source := fmt.Sprintf(`// Code generated by go generate. DO NOT EDIT.
// Manifest: %s.

package manifest

//go:generate go run generate_analysis_compatibility.go

// AnalysisPredecessor returns the matching checksum of the manifest in service.
func AnalysisPredecessor(current string) string {
	if versions := AnalysisManifests(current); len(versions) > 1 {
		return versions[1]
	}
	return ""
}

// AnalysisManifests lists only approved ancestors for the same batch publication state.
func AnalysisManifests(current string) []string {
	switch current {
	case %q:
		return []string{current, %q, %q, %q, %q}
	case %q:
		return []string{current, %q, %q, %q, %q}
	case %q:
		return []string{current, %q, %q, %q, %q}
	}
	return []string{current}
}
`, m.Version, current[0], service[0], history[0], previous[0], legacy,
		current[1], service[1], history[1], previous[1], legacy, current[2], service[2], history[2], previous[2], legacy)
	sourceBytes, err := format.Source([]byte(source))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("analysis_compatibility.go", sourceBytes, 0644); err != nil {
		panic(err)
	}
}
