//go:build ignore

// Run with go generate from the integration worktree with the predecessor in Git.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"

	"github.com/GioNob/ouf-mcp-server/internal/manifest"
)

func checksum(m *manifest.Snapshot) string {
	sum, err := m.Checksum()
	if err != nil {
		panic(err)
	}
	return sum
}

// states returns the checksums of the three approved installation states of
// the published batch capability: ACTIVE, INACTIVE and removed.
func states(m *manifest.Snapshot) [3]string {
	for i, c := range m.Capabilities {
		if c.CapabilityID != "ouf.semantic.search.batch" {
			continue
		}
		if c.PublicationState != "ACTIVE" {
			panic("unexpected published batch baseline")
		}
		active := checksum(m)
		m.Capabilities[i].PublicationState = "INACTIVE"
		inactive := checksum(m)
		m.Capabilities = append(m.Capabilities[:i], m.Capabilities[i+1:]...)
		return [3]string{active, inactive, checksum(m)}
	}
	panic("missing published batch")
}

func main() {
	// The predecessor is the manifest in service (release/d090-t1-mcp, 1.17.0).
	// Each installation state resumes the plans of the same predecessor state.
	const predecessor = "4b395686ab1dccb80e37e63d26a8228b472d05ac"
	raw, err := exec.Command("git", "show", predecessor+":internal/manifest/capabilities.json").Output()
	if err != nil {
		panic(err)
	}
	var old manifest.Snapshot
	if err := json.Unmarshal(raw, &old); err != nil {
		panic(err)
	}
	if old.Version != "1.17.0-published-batch-v1" {
		panic("unexpected predecessor manifest")
	}
	m, err := manifest.Load()
	if err != nil {
		panic(err)
	}
	if m.Version != "1.18.0-onboarding-next-v1" {
		panic("unexpected current manifest")
	}
	current, previous := states(m), states(&old)
	source := fmt.Sprintf(`// Code generated by go generate. DO NOT EDIT.

package manifest

//go:generate go run generate_analysis_compatibility.go

// Each approved batch installation state resumes a plan of the same state of
// the 1.17.0 manifest in service (4b39568).
func AnalysisPredecessor(current string) string {
	switch current {
	case %q:
		return %q
	case %q:
		return %q
	case %q:
		return %q
	}
	return ""
}
`, current[0], previous[0], current[1], previous[1], current[2], previous[2])
	sourceBytes, err := format.Source([]byte(source))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("analysis_compatibility.go", sourceBytes, 0644); err != nil {
		panic(err)
	}
}
