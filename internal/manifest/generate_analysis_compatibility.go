//go:build ignore

// Run with go generate in the integration worktree with both predecessors in Git.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"strings"

	"github.com/GioNob/ouf-mcp-server/internal/manifest"
)

func checksum(m *manifest.Snapshot) string {
	sum, err := m.Checksum()
	if err != nil {
		panic(err)
	}
	return sum
}

func at(commit string) *manifest.Snapshot {
	raw, err := exec.Command("git", "show", commit+":internal/manifest/capabilities.json").Output()
	if err != nil {
		panic(err)
	}
	var m manifest.Snapshot
	if err := json.Unmarshal(raw, &m); err != nil {
		panic(err)
	}
	return &m
}

// Enumerate only the active, inactive and absent published-batch installations.
func states(m *manifest.Snapshot, version string) []string {
	for i, c := range m.Capabilities {
		if c.CapabilityID != "ouf.semantic.search.batch" {
			continue
		}
		if c.PublicationState != "ACTIVE" || m.Version != version {
			panic("unexpected manifest baseline")
		}
		active := checksum(m)
		m.Capabilities[i].PublicationState = "INACTIVE"
		inactive := checksum(m)
		m.Capabilities = append(m.Capabilities[:i], m.Capabilities[i+1:]...)
		return []string{active, inactive, checksum(m)}
	}
	panic("missing batch capability")
}

func main() {
	current, err := manifest.Load()
	if err != nil {
		panic(err)
	}
	prior := states(at("4b395686ab1dccb80e37e63d26a8228b472d05ac"), "1.17.0-published-batch-v1")
	legacy := checksum(at("ea4033ef04579e5bbd59b897133bffa09bc0a803"))
	var out strings.Builder
	out.WriteString(`// Code generated by go generate. DO NOT EDIT.

package manifest

//go:generate go run generate_analysis_compatibility.go

func AnalysisPredecessor(current string) string {
	switch current {
`)
	for i, sum := range states(current, "1.18.0-extraction-unit-v1") {
		fmt.Fprintf(&out, "\tcase %q:\n\t\treturn %q\n", sum, prior[i])
	}
	fmt.Fprintf(&out, "\tcase %q,\n\t\t%q,\n\t\t%q:\n\t\treturn %q\n", prior[0], prior[1], prior[2], legacy)
	out.WriteString("\t}\n\treturn \"\"\n}\n")
	data, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("analysis_compatibility.go", data, 0644); err != nil {
		panic(err)
	}
}
